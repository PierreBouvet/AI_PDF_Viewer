def test_markdown_renderer_math_preservation():
    # 1. Inline math with special characters
    text = "Energy is $E = mc^2$ and probability is $0 < P(X) < 1$."
    html = render_markdown(text)
    assert "$E = mc^2$" in html
    assert "$0 &lt; P(X) &lt; 1$" in html

    # 2. Bracket display math
    bracket_text = "Here is an equation:\n\\[ \\frac{a + b}{c} = d \\]"
    html = render_markdown(bracket_text)
    assert "$$ \\frac{a + b}{c} = d $$" in html

    # 3. Double-dollar display math
    dd_text = "$$\\int_{0}^{\\infty} e^{-x^2} dx = \\frac{\\sqrt{\\pi}}{2}$$"
    html = render_markdown(dd_text)
    assert "$$\\int_{0}^{\\infty} e^{-x^2} dx = \\frac{\\sqrt{\\pi}}{2}$$" in html

    # 4. Bracket inline math
    bi_text = "Let \\( \\alpha + \\beta = 1 \\) be true."
    html = render_markdown(bi_text)
    assert "$ \\alpha + \\beta = 1 $" in html

    # 5. LaTeX environment (align / equation)
    env_text = "\\begin{align}\nx &= 1 \\\\\ny &= 2\n\\end{align}"
    html = render_markdown(env_text)
    assert "$$\\begin{aligned}" in html
    assert "\\end{aligned}$$" in html

    # 6. Code block protection
    code_text = "```bash\nexport VAR=$HOME\necho $1\n```\nAnd inline `$ENV`."
    html = render_markdown(code_text)
    assert "export VAR=$HOME" in html
    assert "echo $1" in html
    assert "<code>$ENV</code>" in html
    # Ensure code blocks were not turned into KaTeX math
    assert "$$export" not in html
    assert "$HOME$" not in html

def test_pdf_generator_real_rendering(qtbot):
    fd, temp_pdf = tempfile.mkstemp(suffix=".pdf")
    os.close(fd)

    html = """<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<link rel="stylesheet" href="katex/katex.min.css">
<script src="katex/katex.min.js"></script>
<script src="katex/contrib/auto-render.min.js"></script>
</head>
<body>
<h1>TeX Test</h1>
<p>Inline: $E = mc^2$</p>
<p>Display: $$\\sum_{i=1}^n i = \\frac{n(n+1)}{2}$$</p>
<div class="ai-tag">[[AI_GENERATED_PAGE]]</div>
<script>
if (window.renderMathInElement) {
    renderMathInElement(document.body, {
        delimiters: [
            {left: "$$", right: "$$", display: true},
            {left: "$", right: "$", display: false}
        ],
        throwOnError: false
    });
}
window.status = "KATEX_DONE";
</script>
</body>
</html>"""

    gen = PDFGenerator(html, temp_pdf)

    with qtbot.waitSignal(gen.finished, timeout=10000) as blocker:
        pass

    assert blocker.args == [True]
    assert os.path.exists(temp_pdf)
    assert os.path.getsize(temp_pdf) > 1000

    import fitz
    doc = fitz.open(temp_pdf)
    assert len(doc) >= 1
    page_text = doc[0].get_text()
    assert "TeX Test" in page_text
    assert "[[AI_GENERATED_PAGE]]" in page_text
    doc.close()

    try:
        os.remove(temp_pdf)
    except OSError:
        pass

def test_append_response_creates_katex_html(qtbot, monkeypatch):
    import keyring
    monkeypatch.setattr(keyring, "get_password", lambda *args, **kwargs: None)

    window = MainWindow()
    qtbot.addWidget(window)
    window.pdf_doc.doc = MagicMock()
    window.pdf_doc.file_path = "/fake/path/document.pdf"

    captured_html = []
    class MockGenerator:
        def __init__(self, html, output_path):
            captured_html.append(html)
            self.finished = MagicMock()

    monkeypatch.setattr("ui.main_window.PDFGenerator", MockGenerator)

    msg_data = {
        "title": "Quantum Mechanics",
        "content": "The wave equation is $i\\hbar \\frac{\\partial}{\\partial t}\\Psi = \\hat{H}\\Psi$."
    }
    window.append_response_to_pdf(msg_data)

    assert len(captured_html) == 1
    html = captured_html[0]
    assert "katex/katex.min.css" in html
    assert "katex/katex.min.js" in html
    assert "katex/contrib/auto-render.min.js" in html
    assert "Quantum Mechanics" in html
    assert "$i\\hbar" in html
    assert "[[AI_GENERATED_PAGE]]" in html
    assert "Generated by" in html
